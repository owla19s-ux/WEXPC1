import assert from 'node:assert/strict';
import { Api } from './api.ts';
import type { Event } from './api.ts';
import { Conversation } from './conversation.ts';
import { alpha, beta } from './adapters.ts';
const api = new Api();
api.register('a', alpha); api.register('b', beta);
const saved = new Map();
const chat = new Conversation(api, (id, result) => saved.set(id, result));
await chat.send('t1', 'a', 'hi'); await chat.send('t2', 'b', 'hi');
assert.deepEqual(saved.get('t1'), saved.get('t2'));
console.log('PASS 1: same conversation consumer, two fixture protocols');
let calls = 0, fail = true;
api.register('counted', (...args) => { calls++; return alpha(...args); });
const flaky = new Conversation(api, () => { if (fail) throw Error('DISK'); });
await assert.rejects(flaky.send('t3', 'counted', 'hi'), /DISK/);
fail = false; flaky.retrySave('t3'); assert.equal(calls, 1); assert.equal(flaky.pending.size, 0);
console.log('PASS 2: failed save retried without resending generation');
api.register('broken', (_input, emit) => { emit({kind:'text', text:'partial'}); throw Error('crash'); });
const broken = await api.start('t4', 'broken', {prompt:'hi', model:'mock'}).complete;
assert.equal(broken.state, 'failed'); assert.equal(broken.remote, 'unknown'); assert.equal(broken.text, 'partial');
api.register('eof', (_input, emit) => emit({kind:'text', text:'partial'}));
assert.equal((await api.start('t5', 'eof', {prompt:'hi', model:'mock'}).complete).state, 'failed');
console.log('PASS 3: crash/EOF preserve partial text and never imply success');
let release!: () => void, late!: (e: Event) => void;
const gate = new Promise<void>(resolve => { release = resolve; });
api.register('held', async (_input, emit) => { late = emit; await gate; emit({kind:'done'}); });
const active = api.start('t6', 'held', {prompt:'hi', model:'mock'});
await Promise.resolve(); active.cancel();
assert.throws(() => api.register('held', beta), /BUSY/);
release(); assert.equal((await active.complete).state, 'succeeded');
assert.equal(api.calls.get('t6')?.cancelRequested, true);
api.register('held', beta); late({kind:'text', text:'stale'});
assert.equal(api.calls.get('t6')?.text, '');
assert.equal((await api.start('t7', 'held', {prompt:'hi', model:'mock'}).complete).text, 'hello');
console.log('PASS 4: busy replacement refused, confirmed finish survives cancellation request, late event ignored');
const cancelled = api.start('t8', 'eof', {prompt:'hi', model:'mock'}); cancelled.cancel();
const cancelledResult = await cancelled.complete;
assert.equal(cancelledResult.state, 'cancelled'); assert.equal(cancelledResult.remote, 'unknown');
assert.throws(() => api.start('t8', 'eof', {prompt:'hi', model:'mock'}), /DUPLICATE/);
console.log('PASS 5: cancellation without confirmed end remains remotely unknown; duplicate call refused');
let observed = '';
api.register('freeze', (input, emit) => { observed = input.model; emit({kind:'done'}); });
const config = {prompt:'hi', model:'old'};
const frozen = api.start('t9', 'freeze', config); config.model = 'new'; await frozen.complete;
assert.equal(observed, 'old');
console.log('PASS 6: admitted input does not follow later caller changes');
